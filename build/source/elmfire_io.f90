! *****************************************************************************
!> Distribute IO jobs equally among available cores (via round robin)
SUBROUTINE SETUP_PARALLEL_IO
! *****************************************************************************

INTEGER :: I,J,N

IF (LEN_TRIM(POPULATION_DENSITY_FILENAME) .GT. 0 .AND. USE_POPULATION_DENSITY) THEN
   USE_POPULATION_DENSITY = .TRUE. 
ELSE
   USE_POPULATION_DENSITY = .FALSE.
ENDIF

IF (LEN_TRIM(REAL_ESTATE_VALUE_FILENAME) .GT. 0 .AND. USE_REAL_ESTATE_VALUE) THEN
   USE_REAL_ESTATE_VALUE = .TRUE.
ELSE
   USE_REAL_ESTATE_VALUE = .FALSE.
ENDIF

IF (LEN_TRIM(LAND_VALUE_FILENAME) .GT. 0 .AND. USE_LAND_VALUE) THEN
   USE_LAND_VALUE = .TRUE. 
ELSE
   USE_LAND_VALUE = .FALSE.
ENDIF

N = NPROC_IRANK0
PARALLEL_IO_RANK(:) = -1
IF (N .GT. 1) THEN

! 1 : WS header
! 2 : ASP header
   PARALLEL_IO_RANK(1) = 0
   PARALLEL_IO_RANK(2) = 1

! 3: WS
! 4: WD
! 5: M1
! 6: M10
! 7: M100
   I = 0
   DO J = 3, 7
      PARALLEL_IO_RANK(J) = I
      I = I + 1
      IF (I .GT. N - 1) I = 0
   ENDDO

! 8: ERC
   IF (USE_ERC) THEN
      I = I + 1
      IF (I .GT. N - 1) I = 0
      PARALLEL_IO_RANK(8) = I
   ENDIF

!  9: LH
! 10: LW 
! 11: MFOL
   DO J = 9, 11
      I = I + 1
      IF (I .GT. N - 1) I = 0
      PARALLEL_IO_RANK(J) = I
   ENDDO

! 12: IGN_MASK
   I = 0
   IF (USE_IGNITION_MASK) THEN
      PARALLEL_IO_RANK(12) = I
      I = I + 1
   ENDIF

! 13: ASP
! 14: CBH
! 15: CBD
! 16: CC
! 17: CH
! 18: DEM
! 19: FBFM
! 20: SLP
! 21: ADJ
! 22: PHI0
   DO J = 13, 22
      PARALLEL_IO_RANK(J) = I
      I = I + 1
      IF (I .GT. N - 1) I = 0
   ENDDO

! 23: POPULATION_DENSITY
   IF (USE_POPULATION_DENSITY) THEN
      I = I + 1
      IF (I .GT. N - 1) I = 0
      PARALLEL_IO_RANK(23) = I
   ENDIF

! 24: REAL_ESTATE_VALUE
   IF (USE_REAL_ESTATE_VALUE) THEN
      I = I + 1
      IF (I .GT. N - 1) I = 0
      PARALLEL_IO_RANK(24) = I
   ENDIF

! 25: LAND_VALUE
   IF (USE_LAND_VALUE) THEN
      I = I + 1
      IF (I .GT. N - 1) I = 0
      PARALLEL_IO_RANK(25) = I
   ENDIF

   ! new suppression model: used 26 for pcl
! 26: PCL
   IF (ENABLE_EXTENDED_ATTACK .AND. EXTENDED_ATTACK_MODEL .EQ. 1) THEN
      I = I + 1
      IF (I .GT. N - 1) I = 0
      PARALLEL_IO_RANK(26) = I
   ENDIF

! 27: SDI
   IF (USE_SDI) THEN
      I = I + 1
      IF (I .GT. N - 1) I = 0
      PARALLEL_IO_RANK(27) = I
   ENDIF

   ! new suppression model

! 28-32: Building spread (previously Hamada model) parameters
   IF (USE_BLDG_SPREAD_MODEL) THEN
      DO J = 28, 32
         I = I + 1
         IF (I .GT. N - 1) I = 0
         PARALLEL_IO_RANK(J) = I
      ENDDO
   ELSE
      IF (ENABLE_SPOTTING .AND. (.NOT. USE_SUPERSEDED_SPOTTING) ) THEN
         I = I + 1
         IF (I .GT. N - 1) I = 0
         PARALLEL_IO_RANK(31) = I
      ENDIF
   ENDIF

! 33: Pyromes
   IF (USE_PYROMES) THEN
      I = I + 1
      IF (I .GT. N - 1) I = 0
      PARALLEL_IO_RANK(33) = I
   ENDIF

! 34: TIMES_BURNED
! 35: SURFACE_FIRE_AREA
! 36: CROWN_FIRE_AREA
! 37: SURFACE_FIRE_VOLUME
! 38: AFFECTED_POPULATION
! 39: AFFECTED_REAL_ESTATE_VALUE
! 40: AFFECTED_LAND_VALUE
   I = 0
   DO J = 34, 40
      PARALLEL_IO_RANK(J) = I
      I = I + 1
      IF (I .GT. N - 1) I = 0
   ENDDO
! 41: Barriers
   IF (USE_BARRIERS) THEN
      I = I + 1
      IF (I .GT. N - 1) I = 0
      PARALLEL_IO_RANK(41) = I
   ENDIF
ELSE
   PARALLEL_IO_RANK(:) = 0
ENDIF

! *****************************************************************************
END SUBROUTINE SETUP_PARALLEL_IO
