      IF (LIVE_MC_IN_PERCENT) MLH%R4(:,:,:) = 0.01 * MLH%R4(:,:,:)
   ENDIF
ENDIF

IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(10)) THEN
   CONSTANT_LW  = -9999.
   IF (USE_CONSTANT_LW) THEN
      CONSTANT_LW = LW_MOISTURE_CONTENT
