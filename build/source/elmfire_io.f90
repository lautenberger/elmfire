! *****************************************************************************
!> Read Weather, Fuel, Topography, Building inputs (constant or raster) in parallel.
SUBROUTINE READ_FUEL_TOPOGRAPHY
! *****************************************************************************

INTEGER :: ICOL, IROW, i, j
REAL :: RX
INTEGER :: IERR
LOGICAL, PARAMETER :: NOISE=.TRUE.
CHARACTER(400) :: FNTIF, FNBSQ, FNHDR, SHELLSTR
LOGICAL :: HDR_EXISTS, BSQ_EXISTS

IF (IRANK_WORLD .EQ. 0) WRITE(*,*) 'Reading fuel and topography rasters'

! When a single multiband landscape GeoTIFF is supplied, convert it to ENVI BSQ
! exactly once (on rank 0) before the individual layers are read. The per-layer
! reads below run on different ranks but all point at this same file, so doing the
! GDAL conversion up front (followed by a barrier) prevents several ranks from
! racing to create the same .bsq/.hdr.
IF (USE_LANDSCAPE_FILE) THEN
   IF (IRANK_WORLD .EQ. 0) THEN
      IF (VRT_INSTEAD_OF_TIF) THEN
         FNTIF = TRIM(FUELS_AND_TOPOGRAPHY_DIRECTORY) // TRIM(LANDSCAPE_FILENAME) // '.vrt'
      ELSE
         FNTIF = TRIM(FUELS_AND_TOPOGRAPHY_DIRECTORY) // TRIM(LANDSCAPE_FILENAME) // '.tif'
      ENDIF
      IF (TRIM(SCRATCH) .EQ. 'null') THEN
         FNHDR = TRIM(FUELS_AND_TOPOGRAPHY_DIRECTORY) // TRIM(LANDSCAPE_FILENAME) // '.hdr'
         FNBSQ = TRIM(FUELS_AND_TOPOGRAPHY_DIRECTORY) // TRIM(LANDSCAPE_FILENAME) // '.bsq'
      ELSE
         FNHDR = TRIM(SCRATCH) // TRIM(LANDSCAPE_FILENAME) // '.hdr'
         FNBSQ = TRIM(SCRATCH) // TRIM(LANDSCAPE_FILENAME) // '.bsq'
      ENDIF
      INQUIRE(FILE=TRIM(FNHDR),EXIST=HDR_EXISTS)
      INQUIRE(FILE=TRIM(FNBSQ),EXIST=BSQ_EXISTS)
      IF (.NOT. HDR_EXISTS .OR. .NOT. BSQ_EXISTS) THEN
         SHELLSTR = TRIM(PATH_TO_GDAL) // 'gdal_translate -q -of ENVI -co "INTERLEAVE=BSQ" ' // TRIM(FNTIF) // " " // TRIM(FNBSQ)
         IF (FEEDBACK_LEVEL .GE. 3) WRITE(*,'(A)') TRIM(SHELLSTR)
         CALL EXECUTE_COMMAND_LINE(TRIM(SHELLSTR))
      ENDIF
   ENDIF
   CALL MPI_BARRIER(MPI_COMM_WORLD, IERR)
ENDIF

IF (USE_IGNITION_MASK .AND. IRANK_WORLD .EQ. PARALLEL_IO_RANK(12)) THEN
   CALL READ_BSQ_RASTER_SLICE (IGN_MASK, FUELS_AND_TOPOGRAPHY_DIRECTORY, IGNITION_MASK_FILENAME, 1, 1)
ENDIF

IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(13)) THEN
   IF (USE_LANDSCAPE_FILE) THEN
      CALL READ_LANDSCAPE_BAND (ASP, FUELS_AND_TOPOGRAPHY_DIRECTORY, LANDSCAPE_FILENAME, 3)
   ELSE
      CALL READ_BSQ_RASTER_SLICE (ASP , FUELS_AND_TOPOGRAPHY_DIRECTORY, ASP_FILENAME, 1, 1)
   ENDIF
   CALL CAST_RASTER_TO_FLOAT(ASP)
ENDIF

IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(14)) THEN
   IF (USE_LANDSCAPE_FILE) THEN
      CALL READ_LANDSCAPE_BAND (CBH, FUELS_AND_TOPOGRAPHY_DIRECTORY, LANDSCAPE_FILENAME, 7)
   ELSE IF (trim(SURFACE_SPREAD_MODEL) .eq. "ROTHERMEL" .or. CBH_FILENAME .ne. ' ') THEN
      CALL READ_BSQ_RASTER_SLICE (CBH , FUELS_AND_TOPOGRAPHY_DIRECTORY, CBH_FILENAME, 1, 1)
   ENDIF
   IF (ASSOCIATED(CBH%R4) .OR. ASSOCIATED(CBH%I2)) THEN
      CALL CAST_RASTER_TO_FLOAT(CBH)
      IF (CBH_TIMES_10 ) WHERE(CBH%R4(:,:,1) .NE. CBH%NODATA_VALUE) CBH%R4(:,:,1) = 0.10*CBH%R4(:,:,1) ! m
   ENDIF
ENDIF

IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(15)) THEN
   IF (USE_LANDSCAPE_FILE) THEN
      CALL READ_LANDSCAPE_BAND (CBD, FUELS_AND_TOPOGRAPHY_DIRECTORY, LANDSCAPE_FILENAME, 8)
   ELSE IF (trim(SURFACE_SPREAD_MODEL) .eq. "ROTHERMEL" .or. CBD_FILENAME .ne. ' ') THEN
      CALL READ_BSQ_RASTER_SLICE (CBD , FUELS_AND_TOPOGRAPHY_DIRECTORY, CBD_FILENAME, 1, 1)
   ENDIF
   IF (ASSOCIATED(CBD%R4) .OR. ASSOCIATED(CBD%I2)) THEN
      CALL CAST_RASTER_TO_FLOAT(CBD)
      IF (CBD_TIMES_100) WHERE(CBD%R4(:,:,1) .NE. CBD%NODATA_VALUE) CBD%R4(:,:,1) = 0.01*CBD%R4(:,:,1) ! kg/m3
   ENDIF
ENDIF

IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(16)) THEN
   IF (USE_LANDSCAPE_FILE) THEN
      CALL READ_LANDSCAPE_BAND (CC, FUELS_AND_TOPOGRAPHY_DIRECTORY, LANDSCAPE_FILENAME, 5)
   ELSE
      CALL READ_BSQ_RASTER_SLICE (CC  , FUELS_AND_TOPOGRAPHY_DIRECTORY, CC_FILENAME, 1, 1)
   ENDIF
   CALL CAST_RASTER_TO_FLOAT(CC)
   IF (CC_IN_PERCENT) WHERE(CC%R4 (:,:,1) .NE. CC%NODATA_VALUE ) CC%R4 (:,:,1) = 0.01*CC%R4 (:,:,1) ! -
ENDIF

IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(17)) THEN
   IF (USE_LANDSCAPE_FILE) THEN
      CALL READ_LANDSCAPE_BAND (CH, FUELS_AND_TOPOGRAPHY_DIRECTORY, LANDSCAPE_FILENAME, 6)
   ELSE
      CALL READ_BSQ_RASTER_SLICE (CH  , FUELS_AND_TOPOGRAPHY_DIRECTORY, CH_FILENAME, 1, 1 )
   ENDIF
   CALL CAST_RASTER_TO_FLOAT(CH)
   IF (CH_TIMES_10  ) WHERE(CH%R4 (:,:,1) .NE. CH%NODATA_VALUE ) CH%R4 (:,:,1) = 0.10*CH%R4 (:,:,1) ! m
ENDIF

IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(18)) THEN
   IF (USE_LANDSCAPE_FILE) THEN
      CALL READ_LANDSCAPE_BAND (DEM, FUELS_AND_TOPOGRAPHY_DIRECTORY, LANDSCAPE_FILENAME, 1)
   ELSE
      CALL READ_BSQ_RASTER_SLICE (DEM , FUELS_AND_TOPOGRAPHY_DIRECTORY, DEM_FILENAME, 1, 1)
   ENDIF
   CALL CAST_RASTER_TO_FLOAT(DEM)
ENDIF

IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(19)) THEN
   IF (USE_LANDSCAPE_FILE) THEN
      CALL READ_LANDSCAPE_BAND (FBFM, FUELS_AND_TOPOGRAPHY_DIRECTORY, LANDSCAPE_FILENAME, 4)
   ELSE
      CALL READ_BSQ_RASTER_SLICE (FBFM, FUELS_AND_TOPOGRAPHY_DIRECTORY, FBFM_FILENAME, 1, 1)
   ENDIF
ENDIF

IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(20)) THEN
   IF (USE_LANDSCAPE_FILE) THEN
      CALL READ_LANDSCAPE_BAND (SLP, FUELS_AND_TOPOGRAPHY_DIRECTORY, LANDSCAPE_FILENAME, 2)
   ELSE
      CALL READ_BSQ_RASTER_SLICE (SLP , FUELS_AND_TOPOGRAPHY_DIRECTORY, SLP_FILENAME, 1, 1)
   ENDIF
   CALL CAST_RASTER_TO_FLOAT(SLP)
ENDIF

IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(21) ) THEN
    CALL READ_BSQ_RASTER_SLICE (ADJ , FUELS_AND_TOPOGRAPHY_DIRECTORY, ADJ_FILENAME, 1, 1)
    WHERE(ADJ%R4 .LT. 0.) ADJ%R4=1.
ENDIF
IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(22) .AND. MODE .NE. 2) THEN
   CALL READ_BSQ_RASTER_SLICE (PHI0 ,FUELS_AND_TOPOGRAPHY_DIRECTORY, PHI_FILENAME, 1, 1)
   WHERE(PHI0%R4(:,:,1) .LT.   -1.1) PHI0%R4(:,:,1) = 1.0
   IF (NOISE) THEN
      DO IROW = 1, PHI0%NROWS
      DO ICOL = 1, PHI0%NCOLS
         CALL RANDOM_NUMBER(RX)
         PHI0%R4(ICOL,IROW,1) = PHI0%R4(ICOL,IROW,1) + 1E-3 * (0.5 - RX)
      ENDDO
      ENDDO
   ENDIF
ENDIF

IF (USE_POPULATION_DENSITY .AND. IRANK_WORLD .EQ. PARALLEL_IO_RANK(23)) CALL READ_BSQ_RASTER_SLICE (POPULATION_DENSITY, FUELS_AND_TOPOGRAPHY_DIRECTORY, POPULATION_DENSITY_FILENAME, 1, 1)
IF (USE_REAL_ESTATE_VALUE  .AND. IRANK_WORLD .EQ. PARALLEL_IO_RANK(24)) CALL READ_BSQ_RASTER_SLICE (REAL_ESTATE_VALUE , FUELS_AND_TOPOGRAPHY_DIRECTORY, REAL_ESTATE_VALUE_FILENAME, 1, 1 )
IF (USE_LAND_VALUE         .AND. IRANK_WORLD .EQ. PARALLEL_IO_RANK(25)) CALL READ_BSQ_RASTER_SLICE (LAND_VALUE        , FUELS_AND_TOPOGRAPHY_DIRECTORY, LAND_VALUE_FILENAME, 1, 1        )
IF (USE_SDI                .AND. IRANK_WORLD .EQ. PARALLEL_IO_RANK(27)) THEN
   CALL READ_BSQ_RASTER_SLICE (SDI               , FUELS_AND_TOPOGRAPHY_DIRECTORY, SDI_FILENAME, 1, 1               )
   CALL CAST_RASTER_TO_FLOAT(SDI)
ENDIF
! new suppression model
IF (ENABLE_EXTENDED_ATTACK .AND. EXTENDED_ATTACK_MODEL .EQ. 1 .AND. IRANK_WORLD .EQ. PARALLEL_IO_RANK(26)) THEN
   CALL READ_BSQ_RASTER_SLICE (PCL, FUELS_AND_TOPOGRAPHY_DIRECTORY, PCL_FILENAME, 1, 1)
   CALL CAST_RASTER_TO_FLOAT(PCL)
ENDIF
! new suppression model


IF (USE_BLDG_SPREAD_MODEL) THEN
   IF (USE_CONSTANT_BLDG_SPREAD_MODEL_PARAMS) THEN
      IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(28)) BLDG_AREA%R4            (:,:,:) = BLDG_AREA_CONSTANT
      IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(29)) BLDG_SEPARATION_DIST%R4 (:,:,:) = BLDG_SEPARATION_DIST_CONSTANT
      IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(30)) BLDG_NONBURNABLE_FRAC%R4(:,:,:) = BLDG_NONBURNABLE_FRAC_CONSTANT
      IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(31)) BLDG_FOOTPRINT_FRAC%R4  (:,:,:) = BLDG_FOOTPRINT_FRAC_CONSTANT
      IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(32)) BLDG_FUEL_MODEL%I2      (:,:,:) = BLDG_FUEL_MODEL_CONSTANT
   ELSE
      IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(28)) CALL READ_BSQ_RASTER_SLICE (BLDG_AREA            , FUELS_AND_TOPOGRAPHY_DIRECTORY, BLDG_AREA_FILENAME, 1, 1 )
      IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(29)) CALL READ_BSQ_RASTER_SLICE (BLDG_SEPARATION_DIST , FUELS_AND_TOPOGRAPHY_DIRECTORY, BLDG_SEPARATION_DIST_FILENAME, 1, 1 )
      IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(30)) CALL READ_BSQ_RASTER_SLICE (BLDG_NONBURNABLE_FRAC, FUELS_AND_TOPOGRAPHY_DIRECTORY, BLDG_NONBURNABLE_FRAC_FILENAME, 1, 1)
      IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(31)) CALL READ_BSQ_RASTER_SLICE (BLDG_FOOTPRINT_FRAC  , FUELS_AND_TOPOGRAPHY_DIRECTORY, BLDG_FOOTPRINT_FRAC_FILENAME, 1, 1)
      IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(32)) CALL READ_BSQ_RASTER_SLICE (BLDG_FUEL_MODEL      , FUELS_AND_TOPOGRAPHY_DIRECTORY, BLDG_FUEL_MODEL_FILENAME, 1, 1)
   ENDIF
ELSE
   IF (ENABLE_SPOTTING .AND. (.NOT. USE_SUPERSEDED_SPOTTING) ) THEN
      IF (USE_CONSTANT_BLDG_SPREAD_MODEL_PARAMS) THEN
         IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(31)) BLDG_FOOTPRINT_FRAC%R4  (:,:,:) = BLDG_FOOTPRINT_FRAC_CONSTANT
      ELSE
         IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(31)) CALL READ_BSQ_RASTER_SLICE (BLDG_FOOTPRINT_FRAC  , FUELS_AND_TOPOGRAPHY_DIRECTORY, BLDG_FOOTPRINT_FRAC_FILENAME, 1, 1)
      ENDIF
   ENDIF
ENDIF

IF (USE_PYROMES .AND. IRANK_WORLD .EQ. PARALLEL_IO_RANK(33)) CALL READ_BSQ_RASTER_SLICE (PYROMES, FUELS_AND_TOPOGRAPHY_DIRECTORY, PYROMES_FILENAME, 1, 1)

IF (USE_BARRIERS .AND. IRANK_WORLD .EQ. PARALLEL_IO_RANK(41)) CALL READ_BSQ_RASTER_SLICE (BARRIER_WIDTH, FUELS_AND_TOPOGRAPHY_DIRECTORY, BARRIER_FILENAME, 1, 1)

CALL MPI_BARRIER(MPI_COMM_WORLD, IERR)

IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(14)) THEN
   if (trim(SURFACE_SPREAD_MODEL) .eq. "CFFDRS" .and. CBH_FILENAME .eq. ' ' .and. .not. USE_LANDSCAPE_FILE) THEN
      do j = 1, size(FBFM%I2,2)
      do i = 1, size(FBFM%I2,1)
         if (FBFM%I2(i,j,1) .eq. FBFM%NODATA_VALUE) then
            CBH%R4(i,j,1) = 0
         else
            CBH%R4(i,j,1) = FUEL_MODEL_TABLE_FBP( FBFM%I2(i,j,1) )%CBH
         endif
      end do
      end do
   endif
ENDIF

IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(15)) THEN
   if (trim(SURFACE_SPREAD_MODEL) .eq. "CFFDRS" .and. CBD_FILENAME .eq. ' ' .and. .not. USE_LANDSCAPE_FILE) THEN
      do j = 1, size(FBFM%I2,2)
      do i = 1, size(FBFM%I2,1)
         if (FBFM%I2(i,j,1) .eq. FBFM%NODATA_VALUE) then
            CBD%R4(i,j,1) = 0
         else
            CBD%R4(i,j,1)=FUEL_MODEL_TABLE_FBP(FBFM%I2(i,j,1))%CFL / (CH%R4(i,j,1) - FUEL_MODEL_TABLE_FBP(FBFM%I2(i,j,1))%CBH + 0.001) ! added a small 0.001 to avoid division by zero
         endif
      end do
      end do
   endif
ENDIF

CALL MPI_BARRIER(MPI_COMM_WORLD, IERR)

IF (NPROC .GT. 1) THEN
   IF (USE_IGNITION_MASK) CALL MPI_BCAST_RASTER_HEADER(IGN_MASK  , PARALLEL_IO_RANK(12), .FALSE.)
   CALL MPI_BCAST_RASTER_HEADER(ASP       , PARALLEL_IO_RANK(13), .FALSE.)
   CALL MPI_BCAST_RASTER_HEADER(CBH       , PARALLEL_IO_RANK(14), .FALSE.)
   CALL MPI_BCAST_RASTER_HEADER(CBD       , PARALLEL_IO_RANK(15), .FALSE.)
   CALL MPI_BCAST_RASTER_HEADER(CC        , PARALLEL_IO_RANK(16), .FALSE.)
   CALL MPI_BCAST_RASTER_HEADER(CH        , PARALLEL_IO_RANK(17), .FALSE.)
   CALL MPI_BCAST_RASTER_HEADER(DEM  , PARALLEL_IO_RANK(18), .FALSE.)
   CALL MPI_BCAST_RASTER_HEADER(FBFM      , PARALLEL_IO_RANK(19), .FALSE.)
   CALL MPI_BCAST_RASTER_HEADER(SLP       , PARALLEL_IO_RANK(20), .FALSE.)
   CALL MPI_BCAST_RASTER_HEADER(ADJ       , PARALLEL_IO_RANK(21), .FALSE.)
   IF (MODE .NE. 2) CALL MPI_BCAST_RASTER_HEADER(PHI0 , PARALLEL_IO_RANK(22), .FALSE.)
   IF (USE_POPULATION_DENSITY) CALL MPI_BCAST_RASTER_HEADER(POPULATION_DENSITY , PARALLEL_IO_RANK(23), .FALSE.)
   IF (USE_REAL_ESTATE_VALUE ) CALL MPI_BCAST_RASTER_HEADER(REAL_ESTATE_VALUE   ,PARALLEL_IO_RANK(24), .FALSE.)
   IF (USE_LAND_VALUE        ) CALL MPI_BCAST_RASTER_HEADER(LAND_VALUE         , PARALLEL_IO_RANK(25), .FALSE.)
   IF (USE_SDI               ) CALL MPI_BCAST_RASTER_HEADER(SDI                , PARALLEL_IO_RANK(27), .FALSE.)
   ! new suppression model
   IF (ENABLE_EXTENDED_ATTACK .AND. EXTENDED_ATTACK_MODEL .EQ. 1) CALL MPI_BCAST_RASTER_HEADER(PCL, PARALLEL_IO_RANK(26), .FALSE.)
   ! new suppression model
   IF (USE_BLDG_SPREAD_MODEL) THEN
      CALL MPI_BCAST_RASTER_HEADER(BLDG_AREA            , PARALLEL_IO_RANK(28), .FALSE.)
      CALL MPI_BCAST_RASTER_HEADER(BLDG_SEPARATION_DIST , PARALLEL_IO_RANK(29), .FALSE.)
      CALL MPI_BCAST_RASTER_HEADER(BLDG_NONBURNABLE_FRAC, PARALLEL_IO_RANK(30), .FALSE.)
      CALL MPI_BCAST_RASTER_HEADER(BLDG_FOOTPRINT_FRAC  , PARALLEL_IO_RANK(31), .FALSE.)
      CALL MPI_BCAST_RASTER_HEADER(BLDG_FUEL_MODEL      , PARALLEL_IO_RANK(32), .FALSE.)
   ENDIF
   IF (USE_PYROMES) CALL MPI_BCAST_RASTER_HEADER(PYROMES, PARALLEL_IO_RANK(33), .FALSE.)
   IF (USE_BARRIERS) CALL MPI_BCAST_RASTER_HEADER(BARRIER_WIDTH, PARALLEL_IO_RANK(41), .FALSE.)
ENDIF

! *****************************************************************************
END SUBROUTINE READ_FUEL_TOPOGRAPHY
! *****************************************************************************

! *****************************************************************************
!> Read split .bsq Weather, Fuel, Topography, Building inputs (constant or raster) in parallel.
SUBROUTINE READ_FUEL_TOPOGRAPHY_TILED
! *****************************************************************************

INTEGER :: ICOL, IROW, j, i
REAL :: RX
INTEGER :: IERR
LOGICAL, PARAMETER :: NOISE=.TRUE.
CHARACTER(400) :: FN

IF (IRANK_WORLD .EQ. 0) WRITE(*,*) 'Reading tiled fuel and topography rasters'

IF (USE_IGNITION_MASK .AND. IRANK_WORLD .EQ. PARALLEL_IO_RANK(12)) THEN
   FN = TRIM(FUELS_AND_TOPOGRAPHY_DIRECTORY) // TRIM(IGNITION_MASK_FILENAME)
   CALL READ_BSQ_RASTER_SLICE_EXISTING_TILED (IGN_MASK,FN, 1, 1)
ENDIF

IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(13)) THEN
   FN = TRIM(FUELS_AND_TOPOGRAPHY_DIRECTORY) // TRIM(ASP_FILENAME)
   CALL READ_BSQ_RASTER_SLICE_EXISTING_TILED (ASP, FN, 1, 1)
   CALL CAST_RASTER_TO_FLOAT(ASP)
ENDIF

IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(14)) THEN
   FN = TRIM(FUELS_AND_TOPOGRAPHY_DIRECTORY) // TRIM(CBH_FILENAME)
   CALL READ_BSQ_RASTER_SLICE_EXISTING_TILED (CBH, FN, 1, 1)
   CALL CAST_RASTER_TO_FLOAT(CBH)
   IF (CBH_TIMES_10 ) WHERE(CBH%R4(:,:,1) .NE. CBH%NODATA_VALUE) CBH%R4(:,:,1) = 0.10*CBH%R4(:,:,1) ! m
ENDIF

IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(15)) THEN
   FN = TRIM(FUELS_AND_TOPOGRAPHY_DIRECTORY) // TRIM(CBD_FILENAME)
   CALL READ_BSQ_RASTER_SLICE_EXISTING_TILED (CBD, FN, 1, 1)
   CALL CAST_RASTER_TO_FLOAT(CBD)
   IF (CBD_TIMES_100) WHERE(CBD%R4(:,:,1) .NE. CBD%NODATA_VALUE) CBD%R4(:,:,1) = 0.01*CBD%R4(:,:,1) ! kg/m3
ENDIF

IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(16)) THEN
   FN = TRIM(FUELS_AND_TOPOGRAPHY_DIRECTORY) // TRIM(CC_FILENAME)
   CALL READ_BSQ_RASTER_SLICE_EXISTING_TILED (CC, FN, 1, 1)
   CALL CAST_RASTER_TO_FLOAT(CC)
   IF (CC_IN_PERCENT) WHERE(CC%R4 (:,:,1) .NE. CC%NODATA_VALUE ) CC%R4 (:,:,1) = 0.01*CC%R4 (:,:,1) ! -
ENDIF

IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(17)) THEN
   FN = TRIM(FUELS_AND_TOPOGRAPHY_DIRECTORY) // TRIM(CH_FILENAME)
   CALL READ_BSQ_RASTER_SLICE_EXISTING_TILED (CH, FN, 1, 1)
   CALL CAST_RASTER_TO_FLOAT(CH)
   IF (CH_TIMES_10  ) WHERE(CH%R4 (:,:,1) .NE. CH%NODATA_VALUE ) CH%R4 (:,:,1) = 0.10*CH%R4 (:,:,1) ! m
ENDIF

IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(18)) THEN
   FN = TRIM(FUELS_AND_TOPOGRAPHY_DIRECTORY) // TRIM(DEM_FILENAME)
   CALL READ_BSQ_RASTER_SLICE_EXISTING_TILED (DEM, FN, 1, 1)
   CALL CAST_RASTER_TO_FLOAT(DEM)
ENDIF

IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(19)) THEN
   FN = TRIM(FUELS_AND_TOPOGRAPHY_DIRECTORY) // TRIM(FBFM_FILENAME)
   CALL READ_BSQ_RASTER_SLICE_EXISTING_TILED (FBFM, FN, 1, 1)
ENDIF

IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(20)) THEN
   FN = TRIM(FUELS_AND_TOPOGRAPHY_DIRECTORY) // TRIM(SLP_FILENAME)
   CALL READ_BSQ_RASTER_SLICE_EXISTING_TILED (SLP, FN, 1, 1)
   CALL CAST_RASTER_TO_FLOAT(SLP)
ENDIF

IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(21) ) THEN
   FN = TRIM(FUELS_AND_TOPOGRAPHY_DIRECTORY) // TRIM(ADJ_FILENAME)
   CALL READ_BSQ_RASTER_SLICE_EXISTING_TILED (ADJ, FN, 1, 1)
   WHERE (ADJ%R4 .LT. 0.) ADJ%R4 = 1.
ENDIF

IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(22) .AND. MODE .NE. 2) THEN
   FN = TRIM(FUELS_AND_TOPOGRAPHY_DIRECTORY) // TRIM(PHI_FILENAME)
   CALL READ_BSQ_RASTER_SLICE_EXISTING_TILED (PHI0, FN, 1, 1)
   IF (NOISE) THEN
      DO IROW = 1, PHI0%NROWS
      DO ICOL = 1, PHI0%NCOLS
         CALL RANDOM_NUMBER(RX)
         PHI0%R4(ICOL,IROW,1) = PHI0%R4(ICOL,IROW,1) + 1E-3 * (0.5 - RX)
      ENDDO
      ENDDO
   ENDIF
ENDIF

IF (USE_POPULATION_DENSITY .AND. IRANK_WORLD .EQ. PARALLEL_IO_RANK(23)) THEN
   FN = TRIM(FUELS_AND_TOPOGRAPHY_DIRECTORY) // TRIM(POPULATION_DENSITY_FILENAME)
   CALL READ_BSQ_RASTER_SLICE_EXISTING_TILED (POPULATION_DENSITY, FN, 1, 1)
ENDIF

IF (USE_REAL_ESTATE_VALUE  .AND. IRANK_WORLD .EQ. PARALLEL_IO_RANK(24)) THEN
   FN = TRIM(FUELS_AND_TOPOGRAPHY_DIRECTORY) // TRIM(REAL_ESTATE_VALUE_FILENAME)
   CALL READ_BSQ_RASTER_SLICE_EXISTING_TILED (REAL_ESTATE_VALUE, FN, 1, 1)
ENDIF

IF (USE_LAND_VALUE         .AND. IRANK_WORLD .EQ. PARALLEL_IO_RANK(25)) THEN
   FN = TRIM(FUELS_AND_TOPOGRAPHY_DIRECTORY) // TRIM(LAND_VALUE_FILENAME)
   CALL READ_BSQ_RASTER_SLICE_EXISTING_TILED (LAND_VALUE, FN, 1, 1)
ENDIF

IF (USE_SDI                .AND. IRANK_WORLD .EQ. PARALLEL_IO_RANK(27)) THEN
   FN = TRIM(FUELS_AND_TOPOGRAPHY_DIRECTORY) // TRIM(SDI_FILENAME)
   CALL READ_BSQ_RASTER_SLICE_EXISTING_TILED (SDI, FN, 1, 1)
   CALL CAST_RASTER_TO_FLOAT(SDI)
ENDIF

! new suppression model
IF (ENABLE_EXTENDED_ATTACK .AND. EXTENDED_ATTACK_MODEL .EQ. 1 .AND. IRANK_WORLD .EQ. PARALLEL_IO_RANK(26)) THEN
   FN = TRIM(FUELS_AND_TOPOGRAPHY_DIRECTORY) // TRIM(PCL_FILENAME)
   CALL READ_BSQ_RASTER_SLICE_EXISTING_TILED (PCL, FN, 1, 1)
   CALL CAST_RASTER_TO_FLOAT(PCL)
ENDIF
! new suppression model

IF (USE_BLDG_SPREAD_MODEL) THEN
   IF (USE_CONSTANT_BLDG_SPREAD_MODEL_PARAMS) THEN
      IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(28)) BLDG_AREA%R4            (:,:,:) = BLDG_AREA_CONSTANT
      IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(29)) BLDG_SEPARATION_DIST%R4 (:,:,:) = BLDG_SEPARATION_DIST_CONSTANT
      IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(30)) BLDG_NONBURNABLE_FRAC%R4(:,:,:) = BLDG_NONBURNABLE_FRAC_CONSTANT
      IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(31)) BLDG_FOOTPRINT_FRAC%R4  (:,:,:) = BLDG_FOOTPRINT_FRAC_CONSTANT
      IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(32)) BLDG_FUEL_MODEL%I2      (:,:,:) = BLDG_FUEL_MODEL_CONSTANT
   ELSE
      IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(28)) THEN
         FN = TRIM(FUELS_AND_TOPOGRAPHY_DIRECTORY) // TRIM(BLDG_AREA_FILENAME)
         CALL READ_BSQ_RASTER_SLICE_EXISTING_TILED (BLDG_AREA, FN, 1, 1)
      ENDIF
      IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(29)) THEN
         FN = TRIM(FUELS_AND_TOPOGRAPHY_DIRECTORY) // TRIM(BLDG_SEPARATION_DIST_FILENAME)
         CALL READ_BSQ_RASTER_SLICE_EXISTING_TILED (BLDG_SEPARATION_DIST, FN, 1, 1)
      ENDIF
      IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(30)) THEN
         FN = TRIM(FUELS_AND_TOPOGRAPHY_DIRECTORY) // TRIM(BLDG_NONBURNABLE_FRAC_FILENAME)
         CALL READ_BSQ_RASTER_SLICE_EXISTING_TILED (BLDG_NONBURNABLE_FRAC, FN, 1, 1)
      ENDIF
      IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(31)) THEN
         FN = TRIM(FUELS_AND_TOPOGRAPHY_DIRECTORY) // TRIM(BLDG_FOOTPRINT_FRAC_FILENAME)
         CALL READ_BSQ_RASTER_SLICE_EXISTING_TILED (BLDG_FOOTPRINT_FRAC, FN, 1, 1)
      ENDIF
      IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(32)) THEN
         FN = TRIM(FUELS_AND_TOPOGRAPHY_DIRECTORY) // TRIM(BLDG_FUEL_MODEL_FILENAME)
         CALL READ_BSQ_RASTER_SLICE_EXISTING_TILED (BLDG_FUEL_MODEL, FN, 1, 1)
      ENDIF
   ENDIF
ENDIF

IF (USE_PYROMES .AND. IRANK_WORLD .EQ. PARALLEL_IO_RANK(33)) THEN
   FN = TRIM(FUELS_AND_TOPOGRAPHY_DIRECTORY) // TRIM(PYROMES_FILENAME)
   CALL READ_BSQ_RASTER_SLICE_EXISTING_TILED (PYROMES, FN, 1, 1)
ENDIF

IF (USE_BARRIERS .AND. IRANK_WORLD .EQ. PARALLEL_IO_RANK(34)) THEN
   FN = TRIM(FUELS_AND_TOPOGRAPHY_DIRECTORY) // TRIM(BARRIER_FILENAME)
   CALL READ_BSQ_RASTER_SLICE_EXISTING_TILED (BARRIER_WIDTH, FN, 1, 1)
ENDIF

CALL MPI_BARRIER(MPI_COMM_WORLD, IERR)

IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(14)) THEN
   if (trim(SURFACE_SPREAD_MODEL) .eq. "CFFDRS" .and. CBH_FILENAME .eq. ' ' .and. .not. USE_LANDSCAPE_FILE) THEN
      do j = 1, size(FBFM%I2,2)
      do i = 1, size(FBFM%I2,1)
         if (FBFM%I2(i,j,1) .eq. FBFM%NODATA_VALUE) then
            CBH%R4(i,j,1) = 0
         else
            CBH%R4(i,j,1) = FUEL_MODEL_TABLE_FBP( FBFM%I2(i,j,1) )%CBH
         endif
      end do
      end do
   endif
ENDIF

IF (IRANK_WORLD .EQ. PARALLEL_IO_RANK(15)) THEN
   if (trim(SURFACE_SPREAD_MODEL) .eq. "CFFDRS" .and. CBD_FILENAME .eq. ' ' .and. .not. USE_LANDSCAPE_FILE) THEN
      do j = 1, size(FBFM%I2,2)
      do i = 1, size(FBFM%I2,1)
         if (FBFM%I2(i,j,1) .eq. FBFM%NODATA_VALUE) then
            CBD%R4(i,j,1) = 0
         else
            CBD%R4(i,j,1)=FUEL_MODEL_TABLE_FBP(FBFM%I2(i,j,1))%CFL / (CH%R4(i,j,1) - FUEL_MODEL_TABLE_FBP(FBFM%I2(i,j,1))%CBH + 0.001) ! added a small 0.001 to avoid division by zero
         endif
      end do
      end do
   endif
ENDIF

CALL MPI_BARRIER(MPI_COMM_WORLD, IERR)

IF (NPROC .GT. 1) THEN
   IF (USE_IGNITION_MASK) CALL MPI_BCAST_RASTER_HEADER(IGN_MASK  , PARALLEL_IO_RANK(12), .FALSE.)
   CALL MPI_BCAST_RASTER_HEADER(ASP       , PARALLEL_IO_RANK(13), .FALSE.)
   CALL MPI_BCAST_RASTER_HEADER(CBH       , PARALLEL_IO_RANK(14), .FALSE.)
   CALL MPI_BCAST_RASTER_HEADER(CBD       , PARALLEL_IO_RANK(15), .FALSE.)
   CALL MPI_BCAST_RASTER_HEADER(CC        , PARALLEL_IO_RANK(16), .FALSE.)
   CALL MPI_BCAST_RASTER_HEADER(CH        , PARALLEL_IO_RANK(17), .FALSE.)
   CALL MPI_BCAST_RASTER_HEADER(DEM  , PARALLEL_IO_RANK(18), .FALSE.)
   CALL MPI_BCAST_RASTER_HEADER(FBFM      , PARALLEL_IO_RANK(19), .FALSE.)
