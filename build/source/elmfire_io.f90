! *****************************************************************************
!> Read split raster contained in FNIN.bsq file and save it to RASTER.
SUBROUTINE READ_BSQ_RASTER_SLICE_EXISTING_TILED(RASTER,FNIN,BANDSTART,BANDEND)
! *****************************************************************************

#ifdef __INTEL_COMPILER
USE IFPORT
#endif

TYPE (RASTER_TYPE), INTENT(INOUT) :: RASTER
CHARACTER(400), INTENT (IN) :: FNIN
INTEGER, INTENT(IN) :: BANDSTART, BANDEND

CHARACTER(400) :: FNHDR, FNBSQ, FNXML
INTEGER :: IOS, IBAND, ITILE, JTILE, IBAND_OUT, NBANDS
INTEGER :: IROW_BIG, IROW_SMALL, ICOL_BIG_LO, ICOL_BIG_HI, IROW_BIG_LO, IROW_BIG_HI
INTEGER :: NCOLS_TILE, NROWS_TILE, NCOLS_FULL, NROWS_FULL
INTEGER*8 :: LRECL
REAL, ALLOCATABLE, DIMENSION(:)   :: RVALUES
REAL, ALLOCATABLE, DIMENSION(:,:) :: RTEMP

INTEGER*2, ALLOCATABLE, DIMENSION(:)   :: I2VALUES
INTEGER*2, ALLOCATABLE, DIMENSION(:,:) :: I2TEMP

CHARACTER(1), DIMENSION(1:3), PARAMETER :: CINDEX = (/'1', '2', '3'/)

IF (BANDSTART .LT. 1) THEN
   WRITE(*,*) '[ERROR] Error processing ', TRIM(FNIN), ' slice band start (', BANDSTART, ') < 1'
   STOP
ENDIF
IF (BANDEND .LE. 0) THEN
   WRITE(*,*) '[ERROR] Error processing ', TRIM(FNIN), ' slice band end (', BANDEND, ') <= 0'
   STOP
ENDIF
IF (BANDSTART .GT. BANDEND) THEN
   WRITE(*,*) '[ERROR] Error processing ', TRIM(FNIN), ' slice band start (', BANDSTART, ') greater than band end (', BANDEND, ')'
   STOP
ENDIF
IF (BANDEND-BANDSTART .gt. WX_BANDS_KEPT_IN_MEM) then
   WRITE(*,*) '[ERROR] Error processing ', TRIM(FNHDR), ' slice band range (', BANDSTART, ') - (',BANDEND,') greater than target range (',WX_BANDS_KEPT_IN_MEM,') '
   STOP
endif

NBANDS = 0   ! real value is computed in the header-set block before any allocation below
DO ITILE = 1, 3
DO JTILE = 1, 3

   FNHDR = TRIM(FNIN) // '_' // CINDEX(ITILE) // '_' // CINDEX(JTILE) // '.hdr'
   FNBSQ = TRIM(FNIN) // '_' // CINDEX(ITILE) // '_' // CINDEX(JTILE) // '.bsq'
   FNXML = TRIM(FNBSQ) // '.aux.xml'

   ! Read header once from the first tile
   IF (ITILE .EQ. 1 .AND. JTILE .EQ. 1 .AND. .NOT. RASTER%HEADERISSET) THEN

      CALL READ_BSQ_HEADER_EXISTING_TILED(RASTER, FNIN)
      RASTER%HEADERISSET = .TRUE.

      ! READ_BSQ_HEADER_EXISTING_TILED currently stores full mosaic dimensions in
      ! RASTER%NCOLS and RASTER%NROWS, so recover tile dimensions here.
      NCOLS_FULL = RASTER%NCOLS
      NROWS_FULL = RASTER%NROWS
      NCOLS_TILE = RASTER%NCOLS / 3
      NROWS_TILE = RASTER%NROWS / 3

      ! This is for bil (because file is dumped as bil):
      RASTER%BYTEORDER = 'I'
      RASTER%LAYOUT    = 'BIL'

      IF (CSV_FIXED_IGNITION_LOCATIONS .AND. ONLY_READ_NEEDED_WX_BANDS .AND. RASTER%NBANDS .GT. 1) THEN
         NBANDS = 1 + IGN_IWX_BAND_HI - IGN_IWX_BAND_LO
      ELSE IF (RASTER%NBANDS .EQ. 1 .OR. RASTER%NBANDS .LT. WX_BANDS_KEPT_IN_MEM) THEN
         NBANDS = RASTER%NBANDS
      ELSE
         NBANDS = WX_BANDS_KEPT_IN_MEM
      endif
   ENDIF ! first tile / first time only

   ! Recover tile/full dimensions on every pass after header has been set
   NCOLS_FULL = RASTER%NCOLS
   NROWS_FULL = RASTER%NROWS
   NCOLS_TILE = RASTER%NCOLS / 3
   NROWS_TILE = RASTER%NROWS / 3

   ICOL_BIG_LO = (ITILE - 1) * NCOLS_TILE + 1
   ICOL_BIG_HI = ICOL_BIG_LO + NCOLS_TILE - 1

   IROW_BIG_LO = (JTILE - 1) * NROWS_TILE + 1
   IROW_BIG_HI = IROW_BIG_LO + NROWS_TILE - 1

   SELECT CASE(TRIM(RASTER%PIXELTYPE))

      CASE('FLOAT')
         IF (.NOT. ASSOCIATED(RASTER%R4)) THEN
            ALLOCATE(RASTER%R4(1:NCOLS_FULL,1:NROWS_FULL,1:NBANDS))
            RASTER%R4(:,:,:) = RASTER%NODATA_VALUE
         ENDIF

         ALLOCATE(RVALUES(1:NCOLS_TILE*NROWS_TILE))
         ALLOCATE(RTEMP  (1:NCOLS_TILE,1:NROWS_TILE))
         ! One BSQ band record = one full tile band
         LRECL = 4_8 * INT(NCOLS_TILE,8) * INT(NROWS_TILE,8)

         OPEN(LUINPUT, FILE=TRIM(FNBSQ), ACCESS='DIRECT', FORM='UNFORMATTED', &
              STATUS='OLD', RECL=LRECL, IOSTAT=IOS)
         IF (IOS .NE. 0) THEN
            WRITE(*,*) 'Problem opening raster file ', TRIM(FNBSQ)
            STOP
         ENDIF

         DO IBAND = BANDSTART, BANDEND
            IBAND_OUT = IBAND - BANDSTART + 1

            READ(LUINPUT, REC=IBAND, IOSTAT=IOS) RVALUES(:)
            IF (IOS .NE. 0) THEN
               WRITE(*,*) '[ERROR] Problem reading band ', IBAND, ' from ', TRIM(FNBSQ)
               WRITE(*,*) 'IOS = ', IOS
               STOP
            ENDIF
            RTEMP(:,:) = RESHAPE(RVALUES, (/NCOLS_TILE, NROWS_TILE/))

            IROW_SMALL = NROWS_TILE
            DO IROW_BIG = IROW_BIG_LO, IROW_BIG_HI
               RASTER%R4(ICOL_BIG_LO:ICOL_BIG_HI, IROW_BIG, IBAND_OUT) = RTEMP(:,IROW_SMALL)
               IROW_SMALL = IROW_SMALL - 1
            ENDDO
         ENDDO
         IF (ALLOCATED(RVALUES)) DEALLOCATE(RVALUES)
         IF (ALLOCATED(RTEMP))   DEALLOCATE(RTEMP)

      CASE('SIGNEDINT')
         IF (.NOT. ASSOCIATED(RASTER%I2)) THEN
            ALLOCATE(RASTER%I2(1:NCOLS_FULL,1:NROWS_FULL,1:NBANDS))
            IF (.NOT. ASSOCIATED(RASTER%R4)) ALLOCATE(RASTER%R4(1:NCOLS_FULL,1:NROWS_FULL,1:NBANDS)) !we are casting it back to a float anyway later.
            RASTER%I2(:,:,:) = NINT(RASTER%NODATA_VALUE,2)
         ENDIF

         ALLOCATE(I2VALUES(1:NCOLS_TILE*NROWS_TILE))
         ALLOCATE(I2TEMP  (1:NCOLS_TILE,1:NROWS_TILE))
         ! ENVI data_type=2 => Int16 => 2 bytes per pixel
         LRECL = 2_8 * INT(NCOLS_TILE,8) * INT(NROWS_TILE,8)

         OPEN(LUINPUT, FILE=TRIM(FNBSQ), ACCESS='DIRECT', FORM='UNFORMATTED', &
              STATUS='OLD', RECL=LRECL, IOSTAT=IOS)
         IF (IOS .NE. 0) THEN
            WRITE(*,*) 'Problem opening raster file ', TRIM(FNBSQ)
            STOP
         ENDIF

         DO IBAND = BANDSTART, BANDEND
            IBAND_OUT = IBAND - BANDSTART + 1

            READ(LUINPUT, REC=IBAND, IOSTAT=IOS) I2VALUES(:)
            IF (IOS .NE. 0) THEN
               WRITE(*,*) '[ERROR] Problem reading band ', IBAND, ' from ', TRIM(FNBSQ)
               WRITE(*,*) 'IOS = ', IOS
               STOP
            ENDIF

            I2TEMP(:,:) = RESHAPE(I2VALUES, (/NCOLS_TILE, NROWS_TILE/))

            IROW_SMALL = NROWS_TILE
            DO IROW_BIG = IROW_BIG_LO, IROW_BIG_HI
               RASTER%I2(ICOL_BIG_LO:ICOL_BIG_HI, IROW_BIG, IBAND_OUT) = I2TEMP(:,IROW_SMALL)
               IROW_SMALL = IROW_SMALL - 1
            ENDDO
         ENDDO
         IF (ALLOCATED(I2VALUES)) DEALLOCATE(I2VALUES)
         IF (ALLOCATED(I2TEMP))   DEALLOCATE(I2TEMP)

      CASE('BYTE','UINT16','INT32','UINT32','DOUBLE')
!        Decoded into 32-bit REAL by READ_BSQ_BAND_R4. PIXELTYPE is relabelled
!        FLOAT only after the tile loop, so every tile decodes with the true type.
         IF (.NOT. ASSOCIATED(RASTER%R4)) THEN
            ALLOCATE(RASTER%R4(1:NCOLS_FULL,1:NROWS_FULL,1:NBANDS))
            RASTER%R4(:,:,:) = RASTER%NODATA_VALUE
         ENDIF

         ALLOCATE(RVALUES(1:NCOLS_TILE*NROWS_TILE))
         ALLOCATE(RTEMP  (1:NCOLS_TILE,1:NROWS_TILE))

         DO IBAND = BANDSTART, BANDEND
            IBAND_OUT = IBAND - BANDSTART + 1
            CALL READ_BSQ_BAND_R4(FNBSQ, IBAND, NCOLS_TILE*NROWS_TILE, RASTER%PIXELTYPE, RVALUES)
            RTEMP(:,:) = RESHAPE(RVALUES, (/NCOLS_TILE, NROWS_TILE/))

            IROW_SMALL = NROWS_TILE
            DO IROW_BIG = IROW_BIG_LO, IROW_BIG_HI
               RASTER%R4(ICOL_BIG_LO:ICOL_BIG_HI, IROW_BIG, IBAND_OUT) = RTEMP(:,IROW_SMALL)
               IROW_SMALL = IROW_SMALL - 1
            ENDDO
         ENDDO
         IF (ALLOCATED(RVALUES)) DEALLOCATE(RVALUES)
         IF (ALLOCATED(RTEMP))   DEALLOCATE(RTEMP)

      CASE DEFAULT
         WRITE(*,*) '[ERROR] READ_BSQ_RASTER_SLICE_EXISTING_TILED: unhandled PIXELTYPE ', &
                    TRIM(RASTER%PIXELTYPE), ' for ', TRIM(FNBSQ)
         STOP

   END SELECT

   CLOSE(LUINPUT, IOSTAT=IOS)

ENDDO
ENDDO

! Numeric types decoded into R4 above are presented as FLOAT to downstream code.
SELECT CASE (TRIM(RASTER%PIXELTYPE))
   CASE ('BYTE','UINT16','INT32','UINT32','DOUBLE')
      RASTER%PIXELTYPE = 'FLOAT'
      RASTER%NBITS = 32
END SELECT

! *****************************************************************************
END SUBROUTINE READ_BSQ_RASTER_SLICE_EXISTING_TILED
