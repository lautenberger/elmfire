9999 FORMAT(I7, ',', I5, ',', 2(F13.2, ','), F8.2, ',', F11.4, ',', 6(F13.1, ','), I7,',',I3, ',', F11.3, ',', 2(E11.3, ','), A, ',', A, ',', E10.3)

